def _make_point(lat: float, lon: float):
    """建立 PostGIS GEOGRAPHY POINT（WKT 格式，不依賴 shapely）。"""
    return WKTElement(f"POINT({lon} {lat})", srid=4326)


async def seed() -> None:
    # 確保表存在
    async with engine.begin() as conn:
        await conn.execute(text("CREATE EXTENSION IF NOT EXISTS postgis"))
        await conn.run_sync(Base.metadata.create_all)

    async with AsyncSessionLocal() as session:
        # ── 1. 取得或建立 Demo 作者 ──────────────────────────────────────────
        result = await session.execute(select(User).where(User.username == DEMO_USERNAME))
        demo_user = result.scalar_one_or_none()

        if demo_user is None:
            demo_user = User(
                username=DEMO_USERNAME,
                email=DEMO_EMAIL,
                display_name=DEMO_DISPLAYNAME,
                hashed_password=DEMO_PW_HASH,
            )
            session.add(demo_user)
            await session.flush()  # 取得 auto-generated id
            print(f"[seed] 建立 Demo 作者：{DEMO_USERNAME}")
        else:
            print(f"[seed] Demo 作者已存在：{DEMO_USERNAME}")

        # ── 2. 檢查是否已 seed ───────────────────────────────────────────────
        count_result = await session.execute(select(func.count()).select_from(CommunitySpot))
        existing_count = count_result.scalar_one()
        if existing_count >= 20:
            print(f"[seed] community_spots 已有 {existing_count} 筆，跳過（避免重複）")
            return

        # ── 3. 塞入台北地點 ──────────────────────────────────────────────────
        spots = []
        for lat, lon, content, image_url, likes, saves in TAIPEI_SPOTS:
            spots.append(
                CommunitySpot(
                    author_id=demo_user.id,
                    location=_make_point(lat, lon),
                    content=content,
                    image_url=image_url,
                    likes_count=likes,
                    saves_count=saves,
                )
            )

        session.add_all(spots)
        await session.commit()
        print(f"[seed] 成功塞入 {len(spots)} 筆台北社群足跡 ✅")
        print("      → Explore 地圖和社群頁現在有內容了！")


if __name__ == "__main__":
    asyncio.run(seed())
